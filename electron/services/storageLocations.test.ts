import { afterEach, describe, expect, it } from 'vitest'
import { mkdtemp, mkdir, writeFile, readFile, rm, symlink } from 'fs/promises'
import { join } from 'path'
import { tmpdir } from 'os'
import { defaultMediaStorageLocation, applyPreparedStorageCleanup, applyPreparedStorageRelocation, cleanupStorageRelocation, discardStorageRelocation, prepareDerivedStorageCleanup, prepareStorageRelocation, resolveRelocatedStoragePath, resolveStorageLocation, storageRelocationStatus, storageUsage } from './storageLocations'
const roots: string[] = []
afterEach(async () => { for (const root of roots.splice(0)) await rm(root, { recursive: true, force: true }) })
async function fixture() {
  const root = await mkdtemp(join(tmpdir(), 'weport-storage-')); roots.push(root)
  const profile = join(root, 'profile'), source = join(root, 'source'), destination = join(root, 'destination')
  await mkdir(join(source, 'nested'), { recursive: true })
  await writeFile(join(source, 'nested', 'memory.md'), '你好 historical evidence')
  return { root, profile, source, destination }
}
describe('transactional storage relocation', () => {
  it('verifies copies before restart and atomically switches only at startup; source stays intact', async () => {
    const x = await fixture(), job = await prepareStorageRelocation(x.profile, 'ai-workspace', x.source, x.destination)
    expect(job.state).toBe('ready')
    expect(resolveStorageLocation(x.profile, 'ai-workspace', x.source)).toBe(x.source)
    expect((await applyPreparedStorageRelocation(x.profile))?.state).toBe('applied')
    expect(resolveStorageLocation(x.profile, 'ai-workspace', x.source)).toBe(job.target)
    expect(await readFile(join(job.target, 'nested', 'memory.md'), 'utf8')).toBe('你好 historical evidence')
    expect(await readFile(join(x.source, 'nested', 'memory.md'), 'utf8')).toBe('你好 historical evidence')
    expect(await storageUsage(job.target)).toEqual({ files: 1, bytes: Buffer.byteLength('你好 historical evidence') })
  })
  it('keeps the original location active if source changes after preparation', async () => {
    const x = await fixture(); await prepareStorageRelocation(x.profile, 'search-index', x.source, x.destination)
    await writeFile(join(x.source, 'new.json'), '{}')
    expect((await applyPreparedStorageRelocation(x.profile))?.state).toBe('failed')
    expect(resolveStorageLocation(x.profile, 'search-index', x.source)).toBe(x.source)
  })
  it('rejects a damaged prepared copy without modifying its source', async () => {
    const x = await fixture(), job = await prepareStorageRelocation(x.profile, 'cache', x.source, x.destination)
    await writeFile(join(job.target, 'nested', 'memory.md'), 'damaged')
    expect((await applyPreparedStorageRelocation(x.profile))?.state).toBe('failed')
    expect(resolveStorageLocation(x.profile, 'cache', x.source)).toBe(x.source)
    await discardStorageRelocation(x.profile)
    expect(storageRelocationStatus(x.profile)).toBeNull()
    expect(await readFile(join(job.target, 'nested', 'memory.md'), 'utf8')).toBe('damaged')
  })
  it('recovers interruption before copy completion and after location commit', async () => {
    const x = await fixture(), job = await prepareStorageRelocation(x.profile, 'cache', x.source, x.destination)
    await writeFile(join(x.profile, 'storage-relocation.json'), JSON.stringify({ ...job, state: 'copying' }))
    expect((await applyPreparedStorageRelocation(x.profile))?.state).toBe('failed')
    await writeFile(join(x.profile, 'storage-relocation.json'), JSON.stringify(job))
    await writeFile(join(x.profile, 'storage-locations.json'), JSON.stringify({ version: 1, paths: { cache: job.target } }))
    expect((await applyPreparedStorageRelocation(x.profile))?.state).toBe('applied')
  })
  it('rejects nested destinations and prevents overwriting a prepared transaction', async () => {
    const x = await fixture()
    await expect(prepareStorageRelocation(x.profile, 'cache', x.source, join(x.source, 'nested'))).rejects.toThrow('separate')
    await prepareStorageRelocation(x.profile, 'cache', x.source, x.destination)
    await expect(prepareStorageRelocation(x.profile, 'cache', x.source, x.destination)).rejects.toThrow('prepared relocation')
  })
  it('relocates external media and exports; persisted references follow successive restarts', async () => {
    const x = await fixture()
    const first = await prepareStorageRelocation(x.profile, 'exports', x.source, x.destination)
    await applyPreparedStorageRelocation(x.profile)
    const second = await prepareStorageRelocation(x.profile, 'exports', first.target, join(x.root, 'destination2'))
    await applyPreparedStorageRelocation(x.profile)
    expect(resolveRelocatedStoragePath(x.profile, join(x.source, 'nested', 'memory.md'))).toBe(join(second.target, 'nested', 'memory.md'))
    expect(resolveRelocatedStoragePath(x.profile, join(x.root, 'source-other', 'file'))).toBe(join(x.root, 'source-other', 'file'))
    await prepareStorageRelocation(x.profile, 'media', x.source, join(x.root, 'media-destination'))
    expect((await applyPreparedStorageRelocation(x.profile))?.kind).toBe('media')
  })
  it('resolves aliased persisted references before and after original cleanup', async () => {
    const x = await fixture(), alias = join(x.root, 'profile-alias')
    await symlink(x.source, alias, 'junction')
    const job = await prepareStorageRelocation(x.profile, 'exports', x.source, x.destination)
    await applyPreparedStorageRelocation(x.profile)
    const reference = join(alias, 'nested', 'memory.md')
    expect(resolveRelocatedStoragePath(x.profile, reference)).toBe(join(job.target, 'nested', 'memory.md'))
    await cleanupStorageRelocation(x.profile, 'original')
    expect(resolveRelocatedStoragePath(x.profile, reference)).toBe(join(job.target, 'nested', 'memory.md'))
    const unrelated = join(x.root, 'source-other', 'missing.md')
    expect(resolveRelocatedStoragePath(x.profile, unrelated)).toBe(unrelated)
  })
  it('cleans only verified duplicate originals and leaves the active unique memory intact', async () => {
    const x = await fixture(), job = await prepareStorageRelocation(x.profile, 'ai-workspace', x.source, x.destination)
    await applyPreparedStorageRelocation(x.profile)
    expect(await cleanupStorageRelocation(x.profile, 'original')).toEqual({ files: 1, bytes: Buffer.byteLength('你好 historical evidence') })
    expect(await readFile(join(job.target, 'nested', 'memory.md'), 'utf8')).toBe('你好 historical evidence')
    expect((await cleanupStorageRelocation(x.profile, 'original')).files).toBe(0)
  })
  it('refuses cleanup when either copy has changed or the source gains unique files', async () => {
    const x = await fixture(), job = await prepareStorageRelocation(x.profile, 'exports', x.source, x.destination)
    await applyPreparedStorageRelocation(x.profile)
    await writeFile(join(x.source, 'unique.txt'), 'unique')
    await expect(cleanupStorageRelocation(x.profile, 'original')).rejects.toThrow('unique')
    await rm(join(x.source, 'unique.txt'))
    await writeFile(join(job.target, 'nested', 'memory.md'), 'new memory')
    await expect(cleanupStorageRelocation(x.profile, 'original')).rejects.toThrow('unique')
    expect(await readFile(join(x.source, 'nested', 'memory.md'), 'utf8')).toBe('你好 historical evidence')
  })
  it('rejects source directories, protected overlaps, symlinks and unsafe journal paths', async () => {
    const x = await fixture()
    await expect(prepareStorageRelocation(x.profile, 'media', x.source, x.destination, [x.source])).rejects.toThrow('protected')
    await mkdir(join(x.source, 'db_storage'))
    await expect(prepareStorageRelocation(x.profile, 'media', x.source, x.destination)).rejects.toThrow('WeChat')
    await rm(join(x.source, 'db_storage'), { recursive: true })
    const job = await prepareStorageRelocation(x.profile, 'exports', x.source, x.destination)
    await writeFile(join(x.profile, 'storage-relocation.json'), JSON.stringify({ ...job, files: [{ ...job.files[0], path: '../escape' }] }))
    expect(() => storageRelocationStatus(x.profile)).toThrow('journal')
    await writeFile(join(x.profile, 'storage-relocation.json'), JSON.stringify(job))
    await rm(join(job.target, 'nested'), { recursive: true })
    await symlink(join(x.source, 'nested'), join(job.target, 'nested'), 'junction')
    await expect(cleanupStorageRelocation(x.profile, 'prepared')).rejects.toThrow('symbolic')
  })
  it('removes only recognized derived artifacts at restart and preserves OCR, models and unique files', async () => {
    const x = await fixture(), index = join(x.profile, 'search-index')
    await mkdir(join(index, 'account', 'shards'), { recursive: true })
    await writeFile(join(index, 'account', 'manifest.json'), '{}')
    await writeFile(join(index, 'account', 'lexical-v1-g1.bin'), 'index')
    await writeFile(join(index, 'account', 'shards', 'message_0.db-b03-g1.json.gz'), 'shard')
    await writeFile(join(index, 'account', 'ocr.txt'), 'unique OCR')
    const prepared = await prepareDerivedStorageCleanup(x.profile, 'search-index', index)
    expect(prepared.files).toHaveLength(3)
    expect((await applyPreparedStorageCleanup(x.profile))?.state).toBe('done')
    expect(await storageUsage(index)).toEqual({ files: 1, bytes: 10 })
    expect(await readFile(join(index, 'account', 'ocr.txt'), 'utf8')).toBe('unique OCR')
    await expect(prepareDerivedStorageCleanup(x.profile, 'ai-data' as any, x.source)).rejects.toThrow('unique')
  })
  it('cancels derived cleanup if content changes between preparation and restart', async () => {
    const x = await fixture(), root = join(x.profile, 'model-cache')
    await mkdir(root, { recursive: true }); await writeFile(join(root, 'models-cache.json'), '{}')
    await prepareDerivedStorageCleanup(x.profile, 'model-cache', root)
    await writeFile(join(root, 'models-cache.json'), '{"changed":true}')
    expect((await applyPreparedStorageCleanup(x.profile))?.state).toBe('failed')
    expect(await readFile(join(root, 'models-cache.json'), 'utf8')).toContain('changed')
  })
})


describe('application managed media defaults', () => {
  it('pins a fresh profile outside Documents even if a legacy folder appears later', async () => {
    const x = await fixture(), documents = join(x.root, 'OneDrive', 'Documents')
    expect(defaultMediaStorageLocation(x.profile, documents)).toBe(join(x.profile, 'media'))
    await mkdir(join(documents, 'WeFlow'), { recursive: true })
    expect(defaultMediaStorageLocation(x.profile, documents)).toBe(join(x.profile, 'media'))
  })
  it('keeps an existing legacy cache reachable without copying or deleting it', async () => {
    const x = await fixture(), documents = join(x.root, 'Documents'), legacy = join(documents, 'WeFlow')
    await mkdir(legacy, { recursive: true }); await writeFile(join(legacy, 'image.dat'), 'legacy')
    expect(defaultMediaStorageLocation(x.profile, documents)).toBe(legacy)
    expect(await readFile(join(legacy, 'image.dat'), 'utf8')).toBe('legacy')
    await rm(legacy, { recursive: true })
    expect(defaultMediaStorageLocation(x.profile, documents)).toBe(legacy)
  })
  it('lets a verified move override the pinned default and retains both copies', async () => {
    const x = await fixture(), documents = join(x.root, 'Documents')
    const fallback = defaultMediaStorageLocation(x.profile, documents)
    await mkdir(fallback, { recursive: true }); await writeFile(join(fallback, 'image.dat'), 'photo')
    const job = await prepareStorageRelocation(x.profile, 'media', fallback, x.destination)
    expect(resolveStorageLocation(x.profile, 'media', fallback)).toBe(fallback)
    expect((await applyPreparedStorageRelocation(x.profile))?.state).toBe('applied')
    expect(resolveStorageLocation(x.profile, 'media', fallback)).toBe(job.target)
    expect(await readFile(join(fallback, 'image.dat'), 'utf8')).toBe('photo')
  })
})
