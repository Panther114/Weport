pub fn run_gui() -> eframe::Result<()> {
    let icon = load_app_icon();
    let mut viewport = egui::ViewportBuilder::default()
        .with_inner_size([1080.0, 720.0])
        .with_min_inner_size([920.0, 600.0])
        .with_title(format!("Weport v{APP_VERSION}"))
        .with_decorations(true);

    if let Some(icon) = icon {
        viewport = viewport.with_icon(icon);
    }

    let options = eframe::NativeOptions {
        viewport,
        ..Default::default()
    };

    eframe::run_native(
        "Weport",
        options,
        Box::new(|cc| {
            setup_style(&cc.egui_ctx);
            setup_fonts(&cc.egui_ctx);
            Ok(Box::new(WeportApp::new(cc)))
        }),
    )
}

fn load_app_icon() -> Option<egui::IconData> {
    // Generated by build.rs from assets/branding/weport-icon.jpg (sole source).
    let bytes = include_bytes!(concat!(env!("OUT_DIR"), "/window-icon.png"));
    let img = image::load_from_memory(bytes).ok()?.into_rgba8();
    let (w, h) = img.dimensions();
    Some(egui::IconData {
        rgba: img.into_raw(),
        width: w,
        height: h,
    })
}

fn setup_fonts(ctx: &egui::Context) {
    let mut fonts = FontDefinitions::default();
    let data = FontData::from_static(include_bytes!("../../src/assets/fonts/weport.ttf"));
    fonts
        .font_data
        .insert("weport".to_owned(), Arc::new(data));
    fonts
        .families
        .entry(FontFamily::Proportional)
        .or_default()
        .insert(0, "weport".to_owned());
    fonts
        .families
        .entry(FontFamily::Monospace)
        .or_default()
        .insert(0, "weport".to_owned());
    ctx.set_fonts(fonts);
}

